-- Provider service zones and directional zone routes.
--
-- Zones are provider-owned records linked to a predefined geography catalog.
-- Routes are independent of zones and are always directional: each
-- From -> To pair must be configured explicitly.

CREATE TABLE geo_zones (
  id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  country_code text NOT NULL DEFAULT 'NG',
  state        text NOT NULL,
  lga          text NOT NULL,
  name         text NOT NULL,
  parent_id    uuid REFERENCES geo_zones (id) ON DELETE SET NULL,
  status       text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive')),
  created_at   timestamptz NOT NULL DEFAULT now(),
  UNIQUE (country_code, state, lga, name)
);

CREATE INDEX geo_zones_state_lga_idx ON geo_zones (lower(state), lower(lga));
CREATE INDEX geo_zones_parent_idx ON geo_zones (parent_id);

